"""Write docs/TRACES.md: walkthroughs of decisions, rebuilt from the traces the agents saved.

    python scripts/trace_walkthroughs.py            # offline simulator (no key needed)
    python scripts/trace_walkthroughs.py --real     # real Meko (writes to the demo datapacks)

Theme 03 asks for trace walkthroughs of at least three decisions; a judge should be able to explain each one from its
trace alone. Each walkthrough shows what the agent decided, the rule, the search it ran in Meko and every memory it
found, with the agent that wrote it.
"""
from __future__ import annotations

from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from payee_sentinel.context import load_env  # noqa: E402
from payee_sentinel.context.local import LocalMeko  # noqa: E402
from payee_sentinel.story import AGENT_NAMES, CHAPTERS, LANES, VENDORS, Story, _n  # noqa: E402

PICKS = [  # (lane, vendor, outcome, why this one)
    ("siloed", "V001", "allow", "The siloed vendor-master agent lets the attacker's bank change through."),
    ("siloed", "V001", "allow", "The siloed payments agent pays the attacker."),
    ("learning2", "V001", "block", "With Meko, the same agent, with the same rule, blocks the change."),
    ("learning2", "V002", "freeze", "Week 2: an approved pattern freezes Bergmann before anyone asks for a change."),
    ("learning2", "V002", "block", "Week 2: the bank change is blocked, and Meko finds the earlier Nordwind case."),
]


def walkthrough(n: int, lane_key: str, d: dict, why: str) -> list[str]:
    v = VENDORS[d["vendor_id"]]
    out = [f"## {n}. {why}", "",
           f"**{LANES[lane_key]} · {AGENT_NAMES[d['agent']]}, {d['at']:%A %d %B %H:%M}: {d['what']}** "
           f"(outcome `{d['outcome']}`, risk {d['risk']})", "",
           f"- **Rule:** {d['rule']}.",
           f"- **Reasoning saved with the decision:** {d['reasoning']}",
           f"- **Search behind it:** `{d['query']}` in `{d['datapack']}`, {_n(len(d['memory_ids']), 'memory').replace('memorys', 'memories')} found."]
    if d.get("related_case"):
        out.append(f"- **Earlier case Meko found for the request:** {d['related_case']} (knowledge base, "
                   f"`context_search`).")
    if d["signals"]:
        out += ["", "| Seen | Written by | Signal | Weight | Detail | Memory id |", "|---|---|---|---|---|---|"]
        for s in sorted(d["signals"], key=lambda s: s.at):
            out.append(f"| {s.at:%a %d %b %H:%M} | {AGENT_NAMES[s.agent]} | `{s.type}` | +{s.weight} | "
                       f"{s.detail.replace('|', '/')} | `{s.memory_id[:8]}` |")
    others = sorted({AGENT_NAMES[s.agent] for s in d["signals"]} - {AGENT_NAMES[d["agent"]]})
    out += ["", f"**Read in two minutes:** {AGENT_NAMES[d['agent']]} decided on {v.name} with "
                f"{_n(len(d['signals']), 'signal')}" + (f", written by {', '.join(others)} and itself." if others
                                                  else ", all its own: no other agent's signals reached it.")]
    return out + [""]


def main() -> None:
    real = "--real" in sys.argv
    if real:
        load_env()
        from payee_sentinel.context.meko import MekoClient
        story = Story(MekoClient)
    else:
        story = Story(LocalMeko)
    for ch in CHAPTERS:
        story.advance()
        if ch.key == "audit":
            story.promote("V001")
    used: set[int] = set()
    lines = ["# Decision trace walkthroughs", "",
             f"Generated by `scripts/trace_walkthroughs.py` from one run of the demo story "
             f"({'real Meko' if real else 'offline simulator of Meko'}, run `{story.run_id}`). Every decision the "
             f"agents make, allow included, is saved in Meko as a conversation turn with its reasoning, its plan, the "
             f"query it ran and the ids of the memories it found (`payee_sentinel/story.py`, `Lane._decision`). "
             f"The siloed lane runs the same agents and rules on the simulator, each agent reading only its own "
             f"signals.", ""]
    n = 0
    for lane_key, vid, outcome, why in PICKS:
        lane = story.lanes[lane_key]
        d = next((d for i, d in enumerate(lane.log) if d["vendor_id"] == vid and d["outcome"] == outcome
                  and id(d) not in used), None)
        if d is None:
            continue
        used.add(id(d))
        n += 1
        lines += walkthrough(n, lane_key, d, why)
    meko = story.lanes["learning2"]
    if meko.learning.get("after"):
        b, a = meko.learning["before"], meko.learning["after"]
        q = meko.asked["V001"]
        lines += [f"## {n + 1}. Meko's self-learning loop closes a gap", "",
                  f"On {q['at']:%A %H:%M} the vendor-master agent asked Meko (`context_search` in `sentinel-patterns`): "
                  f"\"{q['query']}\" Meko graded the match **{b['band']}**. After the analyst confirmed the attack, "
                  f"the auditor agent read Meko's self-learning status, added the confirmed case file to the "
                  f"knowledge base, and asked Meko to replay the question (`selflearning_verify`): **{b['band']} → "
                  f"{a['band']}** (best score {b['best_score']:.2f} → {a['best_score']:.2f}). A week later the same "
                  f"question about Bergmann's request found the Nordwind case "
                  f"({meko.asked['V002']['related'] or 'not found'}).", ""]
    (ROOT / "docs" / "TRACES.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"docs/TRACES.md: {n} walkthroughs" + (" + the self-learning loop" if meko.learning.get("after") else ""))


if __name__ == "__main__":
    main()
